/** "E1 supports C2" / "A1 是 C2 的前提" */
export function relPhrase(rel, a, b, lang) {
  if (rel === 'premise') return lang === 'zh' ? `${a} 是 ${b} 的前提` : `${a} is a premise of ${b}`;
  return `${a} ${tx(`rel_${rel}`, lang)} ${b}`;
}
