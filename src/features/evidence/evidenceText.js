export function tx(key, lang, vars) {
  const e = S[key];
  let s = e ? (lang === 'zh' ? e[1] : e[0]) : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

